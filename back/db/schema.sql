-- Book Catalog schema (PostgreSQL)
-- Order of use: python manage.py migrate -> schema.sql -> seed.sql

-- Start from a clean state (CASCADE also removes dependent foreign keys)
DROP TABLE IF EXISTS review CASCADE;
DROP TABLE IF EXISTS reservation CASCADE;
DROP TABLE IF EXISTS loan CASCADE;
DROP TABLE IF EXISTS librarian CASCADE;
DROP TABLE IF EXISTS member CASCADE;
DROP TABLE IF EXISTS book_author CASCADE;
DROP TABLE IF EXISTS book CASCADE;
DROP TABLE IF EXISTS author CASCADE;
DROP TABLE IF EXISTS publisher CASCADE;
DROP TABLE IF EXISTS category CASCADE;

CREATE TABLE category (
    category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE
);

CREATE TABLE publisher (
    publisher_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL UNIQUE,
    country      TEXT
);

CREATE TABLE author (
    author_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  TEXT NOT NULL,
    birth_year INT,
    country    TEXT
);

CREATE TABLE book (
    book_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            TEXT NOT NULL,
    publication_year INT,
    isbn             TEXT UNIQUE,
    category_id      INT REFERENCES category (category_id),
    publisher_id     INT REFERENCES publisher (publisher_id),
    description      TEXT,
    cover_url        TEXT,
    is_bestseller    BOOLEAN NOT NULL DEFAULT false,
    total_copies     INT NOT NULL CHECK (total_copies >= 0),
    -- a book can never have more available copies than it owns
    available_copies INT NOT NULL CHECK (available_copies >= 0
                                         AND available_copies <= total_copies)
);

-- Many-to-many link: a book can have several authors and vice versa.
-- Django admin cannot edit tables with a composite primary key, so we use
-- a simple id as PK and keep (book_id, author_id) unique instead.
CREATE TABLE book_author (
    book_author_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id        INT NOT NULL REFERENCES book (book_id) ON DELETE CASCADE,
    author_id      INT NOT NULL REFERENCES author (author_id),
    UNIQUE (book_id, author_id)
);

-- user_id links a member to a Django login (auth_user), see the end of file
CREATE TABLE member (
    member_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT UNIQUE NULL,
    full_name     TEXT NOT NULL,
    email         TEXT UNIQUE,
    birth_year    INT,
    registered_at TIMESTAMP DEFAULT now()
);

CREATE TABLE librarian (
    librarian_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name    TEXT NOT NULL,
    email        TEXT UNIQUE
);

CREATE TABLE loan (
    loan_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id      INT REFERENCES book (book_id),
    member_id    INT REFERENCES member (member_id),
    librarian_id INT REFERENCES librarian (librarian_id),
    loan_date    DATE NOT NULL DEFAULT current_date,
    due_date     DATE NOT NULL,
    return_date  DATE NULL,  -- NULL means the book is still out
    CHECK (due_date >= loan_date)
);

CREATE TABLE reservation (
    reservation_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id        INT REFERENCES book (book_id),
    member_id      INT REFERENCES member (member_id),
    reserved_at    TIMESTAMP DEFAULT now(),
    status         TEXT NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'fulfilled', 'cancelled'))
);

CREATE TABLE review (
    review_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id    INT REFERENCES book (book_id) ON DELETE CASCADE,
    member_id  INT REFERENCES member (member_id),
    rating     INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment    TEXT,
    created_at TIMESTAMP DEFAULT now(),
    -- one review per member per book
    UNIQUE (book_id, member_id)
);

-- Indexes for frequent searches and joins
CREATE INDEX idx_book_title ON book (title);
CREATE INDEX idx_book_category ON book (category_id);
CREATE INDEX idx_review_book ON review (book_id);
CREATE INDEX idx_loan_member ON loan (member_id);

-- ------------------------------------------------------------------
-- run AFTER python manage.py migrate (auth_user is created by Django)
-- ------------------------------------------------------------------
ALTER TABLE member ADD FOREIGN KEY (user_id) REFERENCES auth_user (id);
